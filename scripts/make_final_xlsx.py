def fang(r):
    ts = '\n'.join(f'{i+1}. {t}' for i, t in enumerate(r['t']))
    return f"【标题建议】\n{ts}\n\n【口播文案】\n{r['k']}\n\n【改写说明】\n{r['n']}"

